export type MetricKey = keyof typeof METRICS;

/** ทุกคีย์ในพจนานุกรม — ใช้ในเทสต์และตัวช่วยอื่น */
export const METRIC_KEYS = Object.keys(METRICS) as MetricKey[];

/**
 * ข้อความช่วยเหลือของเมตริกหนึ่งตัว — ใช้เป็น `title` บนแถว
 *
 * 🔴 **เขียนให้เหมือนคนพูด ไม่ใช่เหมือนสเปก** (เจ้าของสั่ง 15 ก.ย. 2569:
 * *"ดูเรื่องภาษา สำคัญมาก ไม่เอาภาษา AI"*)
 *
 * ของเดิมต่อเป็นสามบรรทัดมีหัวข้อกำกับ — *"ขอบเขต: …"* / *"กดแล้วไปที่: …"* —
 * อ่านแล้วเหมือนอ่านเอกสารระบบ ไม่ใช่คำอธิบายจากเพื่อนร่วมงาน
 * ⇒ ขอบเขตกลืนไปในวงเล็บท้ายประโยค · ปลายทางขึ้นบรรทัดใหม่ด้วยลูกศร (ไอคอนบนแถว
 * ก็บอกอยู่แล้วว่ากดได้ ไม่ต้องเขียนคำว่า "กดแล้ว")
 */
export function metricHelp(key: MetricKey): string {
  const m: MetricSpec = METRICS[key];
  const head = m.scope ? `${m.what} (${m.scope})` : m.what;
  if (m.landing) return `${head}\n→ ${m.landing}`;
  if (m.landingGap) return `${head}\nยังหาเลขนี้ในหน้าปลายทางไม่ได้ — ${m.landingGap}`;
  return head;
}

/**
 * เมตริกที่ปลายทางยังไม่มีเลขนั้นจริง — **คิวงานที่ยังไม่จบ**
 * มีไว้ให้เทสต์/รายงานหยิบไปนับได้ ว่าเหลืออีกกี่จุดที่คนใหม่จะยังกดแล้วงง
 */
export function metricsWithLandingGap(): MetricKey[] {
  return METRIC_KEYS.filter((k) => Boolean((METRICS[k] as MetricSpec).landingGap));
}
