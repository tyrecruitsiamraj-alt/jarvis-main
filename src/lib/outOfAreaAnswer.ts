const OUT_OF_AREA = [
  /คนละ(พื้นที่|จังหวัด|อำเภอ)/,
  /อยู่ต่างจังหวัด/,
  /(?<!ไม่)(ไกล|ห่างไกล)/,
  /ไม่สะดวก(ใน)?(การ)?เดินทาง/,
  /เดินทาง(ไม่สะดวก|ไม่ไหว|ลำบาก|ไม่ได้)/,
];

export function isOutOfAreaAnswer(summary: string | null | undefined, reply?: string | null): boolean {
  const text = `${summary ?? ''} ${reply ?? ''}`.replace(/\s+/g, '');
  if (!text) return false;
  return OUT_OF_AREA.some((re) => re.test(text));
}
