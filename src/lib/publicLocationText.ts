/**
 * คำที่เป็น **หัวของข้อมูลติดต่อ/ข้อมูลภายใน** — เจอคำไหนก่อน ตัดตั้งแต่ตรงนั้นทิ้ง
 *
 * ⚠️ ตัดทั้งท้ายเพราะของพวกนี้อยู่ **ท้ายข้อความเสมอ** ในของจริง (ที่อยู่มาก่อน
 * แล้วค่อยต่อด้วยคนติดต่อ) · ตัดเฉพาะคำแล้วเหลือเศษชื่อคนลอยไว้จะแย่กว่าเดิม
 */
const CONTACT_MARKERS = [
  'ทะเบียนรถ',
  'เบอร์ติดต่อ',
  'เบอร์โทร',
  'เบอร์ ',
  'โทร.',
  'ผู้ติดต่อ',
  'ติดต่อคุณ',
  'ผู้จัดการสาขา',
  'ผู้ช่วย',
] as const;

/**
 * เบอร์โทรไทย — `096-226-1515` · `0817101603` · `02 296 6523` · `+66812345678`
 * ⚠️ ต้องไม่ไปจับเลขเอกสาร (`WF 000127/2026`) หรือรหัสสาขา (`629`) — จึงบังคับ
 * ความยาวหลักรวมแบบเบอร์จริง และไม่ยอมให้มี `/` คั่น
 */
const PHONE_RE = /(?:\+?66|0)[\s-]?\d{1,2}[\s-]?\d{3}[\s-]?\d{3,4}(?!\d)/;

/** ตัวคั่นที่ติดอยู่ท้ายหลังตัด — เก็บกวาดให้จบประโยคสวย ๆ */
const TRAILING_JUNK_RE = /[\s,;:·\-–—(]+$/;

/**
 * คืนข้อความสถานที่ที่ **ไม่มีชื่อ/เบอร์คน** · ไม่มีอะไรต้องตัด = คืนค่าเดิมทั้งดุ้น
 *
 * คืนสตริงว่างเมื่อตัดแล้วไม่เหลืออะไร — ผู้เรียกตัดสินเองว่าจะใส่ค่าว่างหรือคงของเดิม
 */
export function scrubPublicLocation(raw: string | null | undefined): string {
  if (typeof raw !== 'string') return '';
  const text = raw.trim();
  if (!text) return '';

  let cut = text.length;

  for (const marker of CONTACT_MARKERS) {
    const i = text.indexOf(marker);
    if (i >= 0 && i < cut) cut = i;
  }

  const phone = PHONE_RE.exec(text);
  if (phone && phone.index < cut) cut = phone.index;

  if (cut >= text.length) return text;
  return text.slice(0, cut).replace(TRAILING_JUNK_RE, '').trim();
}

/** มีของที่ต้องตัดไหม — ใช้บอกคนกรอกว่าระบบตัดอะไรออกไปให้ */
export function hasContactInfo(raw: string | null | undefined): boolean {
  if (typeof raw !== 'string' || !raw.trim()) return false;
  return scrubPublicLocation(raw) !== raw.trim();
}
