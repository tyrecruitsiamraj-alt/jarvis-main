import type { JobRequest } from '@/types';

/**
 * ชื่อหน่วยงานบนจอ — **ชื่อจุดทำงานชื่อเดียว**
 *
 * 🔴 เจ้าของสั่งแก้ทั้งระบบ 3 ก.ย. 2569 หลังเจอใบขอไซต์ `69LBDL0044` ขึ้นจอว่า
 * *"บริษัท สมิติเวช ศรีราชา จำกัด (สำนักงานใหญ่)"* ทั้งที่คนต้องไปทำงานที่
 * **สมิติเวช ชลบุรี** (โรงพยาบาลชลบุรีจดทะเบียนใต้บริษัทศรีราชา)
 *
 * กติกา (เจ้าของสั่งย้ำ 3 ก.ย. 2569 — *"เอาแค่ สมิติเวช ชลบุรี มา ขึ้นคู่สัญญาไม่ต้อง
 * เดี๋ยวงง"*):
 * 1. โชว์ **ชื่อเดียว** = จุดทำงาน (`work_site_name`) เพราะคำถามแรกของทุกคนคือ *ไปที่ไหน*
 * 2. ไม่มีจุดทำงาน (ใบขอล่วงหน้าไม่มีไซต์) ⇒ ถอยไปชื่อคู่สัญญา (`unit_name`) แทน
 * 3. **ห้ามเอาชื่อคู่สัญญามาต่อท้าย/ขึ้นบรรทัดสอง** — เคยทำแล้วเจ้าของสั่งเอาออก
 *    ชื่อคู่สัญญายังอยู่ใน ERP ตามเดิม ใครต้องใช้ไปดูที่ ERP
 *
 * 🔴 **ห้ามเอาฟังก์ชันพวกนี้ไปทำกุญแจแมตช์/จัดกลุ่ม** — `unit_name` เป็นตัวที่
 * `jobPenalty` แมตช์กับ `client_name` ของ WL ที่บันทึกไว้แล้ว ต้องใช้ค่าดิบเสมอ
 */
type UnitSource = Pick<JobRequest, 'unit_name'> & { work_site_name?: string | null };

/** ชื่อหน่วยงานที่โชว์ — จุดทำงานถ้ามี ไม่มีก็ถอยไปชื่อคู่สัญญา */
export function unitLabel(job: UnitSource): string {
  const site = (job.work_site_name ?? '').trim();
  if (site) return site;
  return (job.unit_name ?? '').trim() || '—';
}

/**
 * ที่ที่ใส่ได้บรรทัดเดียว (ตารางแคบ · CSV · แจ้งเตือน) — ชื่อเดียวกับ `unitLabel`
 * มีไว้เพื่อให้จุดที่ต่อสตริงเองอ่านง่ายว่ากำลังใช้ชื่อหน่วยงานชุดเดียวกัน
 */
export function unitOneLine(job: UnitSource): string {
  return unitLabel(job);
}
