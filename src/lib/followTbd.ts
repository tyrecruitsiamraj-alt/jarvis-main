/**
 * "ยังไม่ชัวร์เวลา" (134) — ค่าในฟอร์มเป็นวันล้วน (YYYY-MM-DD) · เวลาไว้เติมทีหลัง
 *
 * 🔴 สองสายวันเดียวกันได้ค่าเหมือนกันเป๊ะ ⇒ ตัวตัดเวลาซ้ำรวมเป็นสายเดียว + เลขสายชนกัน
 * (เจ้าของเจอ 5 ต.ค. 2569: *"ขึ้นสายโทรครั้งที่ 1 ทั้ง2สายเลย ทั้งที่ตอนเพิ่มเลือก สาย1 สาย2"*)
 * ⇒ ให้แต่ละสายมีเวลาแทนของตัวเอง = เที่ยงคืน + ลำดับช่องเป็นนาที (เรียงตามลำดับที่กรอก ไม่ชนกัน)
 * จอโชว์ "ยังไม่ระบุเวลา" จากธง time_tbd อยู่แล้ว — นาทีแทนไม่โผล่ให้คนเห็น
 */
const DATE_ONLY = /^\d{4}-\d{2}-\d{2}$/;

export function tbdPlaceholderAts(values: readonly string[], modes: ReadonlyArray<string | undefined>): string[] {
  return values.map((v, i) =>
    modes[i] === 'tbd' && DATE_ONLY.test(v) ? `${v}T00:${String(Math.min(i, 59)).padStart(2, '0')}` : v,
  );
}
