/**
 * ตัดคำทักในบทชวนงาน (เจ้าของเลือก 18 ต.ค. 2569 จากข้อที่พักไว้ 17 ต.ค.)
 * Lumos ทัก แนะนำตัว และถามว่าสะดวกคุยไหมเองทุกสายของบทชวนงาน (ดูบทสนทนาจริง 17 ต.ค.) — บทของเราเข้าเรื่องเลย
 * บทติดตาม/ส่งคนแทน คงคำทักไว้ (Lumos เอาคำทักของเราเป็นประโยคเปิด · มีชื่อเจ้าหน้าที่ที่เจ้าของสั่งคำต่อคำ 1 ก.ย.)
 */
import { describe, expect, it } from 'vitest';
import { CALL_SCRIPT_TEMPLATES as T } from '../../api/_lib/lumosCallScript.templates';

describe('บทชวนงานไม่ทักซ้ำ', () => {
  it('สัมภาษณ์เบื้องต้น · เสนองาน · ทักทายทั่วไป · คำถามสำรอง — ประโยคแรกไม่มีสวัสดี/ชื่อบริษัท/ขอเวลา', () => {
    for (const first of [T.สัมภาษณ์เบื้องต้น[0], T.เสนองาน[0], T.ทักทายทั่วไป[0], T.คำถามสำรอง]) {
      expect(first).not.toContain('สวัสดี');
      expect(first).not.toContain('{ผู้โทร}');
      expect(first).not.toContain('2-3 นาที');
    }
  });
  it('บทติดตาม/ส่งคนแทน ยังทักด้วยชื่อเจ้าหน้าที่', () => {
    expect(T.ติดตาม[0]).toContain('สวัสดีค่ะ {ชื่อเจ้าหน้าที่}');
    expect(T.ติดตามรอบถัดไป[0]).toContain('สวัสดีค่ะ {ชื่อเจ้าหน้าที่}');
  });
});
