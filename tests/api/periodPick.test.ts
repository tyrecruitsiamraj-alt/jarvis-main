// @vitest-environment node
/**
 * ═══ ตัวเลือกช่วงเวลาแบบใช้ง่าย (เจ้าของสั่ง 30 ก.ย. 2569) ═══
 * > *"calendar มันดูยาก … เลือกช่วงวันได้ หรือ จะดูแค่วันไหนได้"* ·
 * > *"ดูรายเดือนต้องเห็นวันที่ 1-30 · รายสัปดาห์เห็น 1-7 · default ย้อนหลัง 7 วัน"*
 * 🔴 ด่าน: สัปดาห์ = จันทร์ถึงอาทิตย์ · เดือน = วันที่ 1 ถึงวันสุดท้าย (รวมกุมภา/ข้ามปี) · ป้ายเป็นภาษาคน ปี พ.ศ.
 */
import { describe, expect, it } from 'vitest';
import {
  QUICK_PERIODS,
  lastDays,
  mondayOf,
  monthOf,
  periodLabel,
  periodModeOf,
  quickKeyOf,
  rangeText,
  rangeTextFull,
  thaiDate,
  unitCount,
  unitSpan,
  weekOf,
  yearWindow,
} from '../../src/lib/periodPick.js';

const TODAY = '2026-09-30'; // วันพุธ

describe('สัปดาห์ = จันทร์ถึงอาทิตย์', () => {
  it('วันพุธ → จันทร์ที่ 28 ถึงอาทิตย์ที่ 4', () => {
    expect(mondayOf(TODAY)).toBe('2026-09-28');
    expect(weekOf(TODAY)).toEqual({ from: '2026-09-28', to: '2026-10-04' });
  });
  it('วันอาทิตย์ยังเป็นสัปดาห์ที่เริ่มจันทร์ก่อนหน้า', () => {
    expect(weekOf('2026-10-04')).toEqual({ from: '2026-09-28', to: '2026-10-04' });
  });
});

describe('เดือน = วันที่ 1 ถึงวันสุดท้าย', () => {
  it.each([
    ['2026-09-15', { from: '2026-09-01', to: '2026-09-30' }],
    ['2026-02-10', { from: '2026-02-01', to: '2026-02-28' }],
    ['2028-02-10', { from: '2028-02-01', to: '2028-02-29' }],
    ['2026-12-31', { from: '2026-12-01', to: '2026-12-31' }],
  ])('%s', (ymd, want) => {
    expect(monthOf(ymd)).toEqual(want);
  });
});

describe('ปุ่มลัด — ตัวแรกคือค่าตั้งต้น 7 วันล่าสุด', () => {
  it('7 วันล่าสุดรวมวันนี้', () => {
    expect(QUICK_PERIODS[0].key).toBe('last7');
    expect(QUICK_PERIODS[0].build(TODAY)).toEqual({ from: '2026-09-24', to: '2026-09-30' });
    expect(lastDays(7, TODAY)).toEqual({ from: '2026-09-24', to: '2026-09-30' });
  });
  it('รู้ว่าช่วงนี้ตรงกับปุ่มไหน', () => {
    expect(quickKeyOf({ from: '2026-09-24', to: '2026-09-30' }, TODAY)).toBe('last7');
    expect(quickKeyOf({ from: null, to: null }, TODAY)).toBe('all');
    expect(quickKeyOf({ from: '2026-09-01', to: '2026-09-30' }, TODAY)).toBe('thisMonth');
    expect(quickKeyOf({ from: '2026-09-02', to: '2026-09-05' }, TODAY)).toBeNull();
  });
});

describe('ป้ายบนปุ่มเป็นภาษาคนพูด ปี พ.ศ.', () => {
  it.each([
    [{ from: null, to: null }, 'ทั้งหมด'],
    [{ from: '2026-09-24', to: '2026-09-30' }, '7 วันล่าสุด'],
    [{ from: '2026-09-30', to: '2026-09-30' }, 'วันนี้'],
    [{ from: '2026-09-29', to: '2026-09-29' }, 'เมื่อวาน'],
    [{ from: '2026-09-28', to: '2026-10-04' }, 'สัปดาห์นี้'],
    [{ from: '2026-09-01', to: '2026-09-30' }, 'เดือนนี้'],
    [{ from: '2026-09-05', to: '2026-09-05' }, '5 ก.ย. 2569'],
    [{ from: '2026-09-14', to: '2026-09-20' }, 'สัปดาห์ 14–20 ก.ย. 2569'],
    [{ from: '2026-08-01', to: '2026-08-31' }, 'สิงหาคม 2569'],
    [{ from: '2026-09-02', to: '2026-09-10' }, '2–10 ก.ย. 2569'],
    [{ from: '2026-08-25', to: '2026-09-03' }, '25 ส.ค. – 3 ก.ย. 2569'],
    [{ from: '2025-12-25', to: '2026-01-03' }, '25 ธ.ค. 2568 – 3 ม.ค. 2569'],
    [{ from: '2026-01-01', to: '2026-12-31' }, 'ปี 2569'],
    [{ from: '2025-01-01', to: '2025-12-31' }, 'ปี 2568'],
  ])('%j → %s', (win, want) => {
    expect(periodLabel(win, TODAY)).toBe(want);
  });

  it('30 วันล่าสุด (วันที่ที่ไม่ชนกับ "เดือนนี้")', () => {
    // 30 ก.ย. นับย้อน 30 วัน = 1–30 ก.ย. ตรงกับเดือนนี้พอดี ⇒ ลองวันกลางเดือน
    expect(periodLabel({ from: '2026-08-17', to: '2026-09-15' }, '2026-09-15')).toBe('30 วันล่าสุด');
  });

  it('ส่วนย่อย', () => {
    expect(thaiDate('2026-01-05')).toBe('5 ม.ค. 2569');
    expect(rangeText('2026-09-05', '2026-09-05')).toBe('5 ก.ย. 2569');
  });
});

describe('เปิดปฏิทินรอบถัดไปให้ตรงแบบเดิม', () => {
  it.each([
    [{ from: '2026-09-05', to: '2026-09-05' }, 'day'],
    [{ from: '2026-09-14', to: '2026-09-20' }, 'week'],
    [{ from: '2026-09-01', to: '2026-09-30' }, 'month'],
    [{ from: '2026-09-02', to: '2026-09-10' }, 'range'],
    [{ from: '2026-01-01', to: '2026-12-31' }, 'year'],
    [{ from: '2026-01-01', to: '2026-12-30' }, 'range'],
    [{ from: null, to: null }, 'range'],
  ])('%j → %s', (win, want) => {
    expect(periodModeOf(win)).toBe(want);
  });
});

describe('รอบ 17 — ทั้งปี + หัวกราฟบอกเดือน/ช่วงวันด้วยชื่อเดือนเต็ม', () => {
  it('ทั้งปี = 1 ม.ค. ถึง 31 ธ.ค.', () => {
    expect(yearWindow(2026)).toEqual({ from: '2026-01-01', to: '2026-12-31' });
  });
  it.each([
    ['2026-09-30', '2026-09-30', '30 กันยายน 2569'],
    ['2026-09-24', '2026-09-30', '24–30 กันยายน 2569'],
    ['2026-09-01', '2026-09-30', '1–30 กันยายน 2569'],
    ['2026-08-28', '2026-09-03', '28 สิงหาคม – 3 กันยายน 2569'],
    ['2025-12-25', '2026-01-03', '25 ธันวาคม 2568 – 3 มกราคม 2569'],
  ])('%s – %s → %s', (from, to, want) => {
    expect(rangeTextFull(from, to)).toBe(want);
  });
});

describe('รอบ 18 — เลือกหลายหน่วยมาเทียบ (กดครั้งแรก = หน่วยเดียว · กดอีกครั้ง = ถึงหน่วยนั้น)', () => {
  it('ช่วงครอบหน่วยของสองวันที่กด · กดกลับหัวก็ได้', () => {
    expect(unitSpan('month', '2026-09-10', '2026-10-02')).toEqual({ from: '2026-09-01', to: '2026-10-31', unit: 'month' });
    expect(unitSpan('month', '2026-10-02', '2026-09-10')).toEqual({ from: '2026-09-01', to: '2026-10-31', unit: 'month' });
    expect(unitSpan('week', '2026-09-15', '2026-09-30')).toEqual({ from: '2026-09-14', to: '2026-10-04', unit: 'week' });
    expect(unitSpan('year', '2025-03-01', '2026-01-01')).toEqual({ from: '2025-01-01', to: '2026-12-31', unit: 'year' });
    expect(unitSpan('day', '2026-09-30', '2026-09-28')).toEqual({ from: '2026-09-28', to: '2026-09-30', unit: 'day' });
    // กดครั้งเดียว = หน่วยเดียว
    expect(unitSpan('month', '2026-09-01', '2026-09-01')).toEqual({ from: '2026-09-01', to: '2026-09-30', unit: 'month' });
  });

  it('นับหน่วยตามปฏิทิน', () => {
    expect(unitCount('month', '2026-09-01', '2026-10-31')).toBe(2);
    expect(unitCount('month', '2025-12-01', '2026-01-31')).toBe(2);
    expect(unitCount('week', '2026-09-14', '2026-10-04')).toBe(3);
    expect(unitCount('year', '2025-01-01', '2026-12-31')).toBe(2);
    expect(unitCount('day', '2026-09-24', '2026-09-30')).toBe(7);
    expect(unitCount('month', '2026-10-01', '2026-09-01')).toBe(0);
  });

  it.each([
    [{ from: '2026-09-01', to: '2026-10-31', unit: 'month' as const }, 'ก.ย. – ต.ค. 2569'],
    [{ from: '2025-12-01', to: '2026-01-31', unit: 'month' as const }, 'ธ.ค. 2568 – ม.ค. 2569'],
    [{ from: '2025-01-01', to: '2026-12-31', unit: 'year' as const }, 'ปี 2568 – 2569'],
    [{ from: '2026-09-14', to: '2026-10-04', unit: 'week' as const }, '3 สัปดาห์ 14 ก.ย. – 4 ต.ค. 2569'],
    // หน่วยเดียว = ป้ายเดิมของช่วงแบบนั้น
    [{ from: '2026-08-01', to: '2026-08-31', unit: 'month' as const }, 'สิงหาคม 2569'],
    [{ from: '2026-01-01', to: '2026-12-31', unit: 'year' as const }, 'ปี 2569'],
    [{ from: '2026-09-24', to: '2026-09-30', unit: 'day' as const }, '7 วันล่าสุด'],
  ])('%j → %s', (win, want) => {
    expect(periodLabel(win, TODAY)).toBe(want);
  });
});
