--
-- เจ้าของถาม 13 ส.ค. 2569: "รายชื่อเข้ามาตามกล่องแล้วถ้างานนั้นปิดไปแล้วทำไงดี
-- ไม่ได้อยากให้รายชื่อมันหายไปอะ" → เคาะ: **เก็บคนไว้ที่คลังกลาง**
--
-- ปัญหาที่ตรวจเจอ: สิทธิ์เห็นใบสมัครคำนวณจาก `loadScopedJobIdSet()` ซึ่งสร้างจาก
-- **ใบขอที่เปิดอยู่เท่านั้น** → พอใบขอปิด job_id หลุดจาก scope แล้วคนที่ถูกล็อก BU
-- **มองไม่เห็นใบสมัครนั้นอีกเลยทั้งระบบ** (ไม่ใช่แค่กดจากการ์ดไม่ได้) · admin ยังเห็นครบ
--
-- ทางแก้: ใบสมัครจำรหัสแผนกไว้ตั้งแต่ตอนสมัคร แล้วสิทธิ์เทียบจากคอลัมน์นี้ได้ตรง ๆ
-- ไม่ต้องพึ่งว่าใบขอยังเปิดอยู่ไหม · สิทธิ์ BU ยังคุมเหมือนเดิมทุกอย่าง ไม่ได้ผ่อนให้ใคร
--
-- ⚠️ ค่า null = ใบเก่าที่ยังไม่รู้แผนก (หรือใบที่เจ้าหน้าที่คีย์เองโดยไม่ผูกใบขอ)
-- ฝั่ง API ยังถอยไปเทียบ job_id ให้อยู่ จึงไม่มีใครมองไม่เห็นของที่เคยเห็น
