-- ประเภทหน่วยงาน: ราชการ / เอกชน (เจ้าของสั่ง 25 ส.ค. 2569)
--
-- 🔴 ทำไมเก็บฝั่งเราแทนที่จะอ่านจาก ERP:
-- ERP มีตารางแม่ `ms_customer_group` อยู่แล้ว (001 เอกชน · 002 ราชการ · 003 กฟภ. ·
-- 004 รัฐวิสาหกิจ · 005 บุคคลธรรมดา · 006 ขายทอดตลาด · 007 ศาสนสถาน) และใบขอเข้าถึง
-- ได้ผ่าน `st_site_contract_p1.customer_group_code` — **แต่วัดจริงแล้วใช้ไม่ได้ตรง ๆ**:
--   เอกชน 11,660 · ราชการ 2,950 · กฟภ. 2,671 · **ไม่รู้กลุ่ม (ค่าว่าง) 2,804 ใบ**
-- เจ้าของเคาะ 25 ส.ค. 2569 ว่า **เอา 2 ตัวเลือกและให้คนระบุเอง** (ไม่ derive จาก ERP)
-- เพราะ กฟภ./รัฐวิสาหกิจ จะนับเป็นฝั่งไหนเป็นเรื่องนโยบาย ไม่ใช่เรื่องข้อมูล
--
-- 🔴 คีย์เป็น `site_code` ไม่ใช่เลขที่ใบขอ:
-- "ราชการ/เอกชน" เป็นคุณสมบัติของ**หน่วยงาน** ไม่ใช่ของใบขอแต่ละใบ
-- วัดจริง: ใบขอที่เปิดอยู่ 293 ใบ มาจากหน่วยงานแค่ **138 แห่ง**
-- ⇒ กรอกครั้งเดียวใช้ทั้งไซต์ (ถ้าคีย์รายใบต้องกรอก 293 ครั้ง และใบใหม่ของไซต์เดิมจะว่างอีก)
-- แมป job_id → site_code มีอยู่แล้วที่ `job_site_map` (migration 106)
--
-- ⚠️ ไม่มีแถว = **ยังไม่ระบุ** ไม่ใช่ "เอกชน" — ห้ามตั้ง default ให้ค่าใดค่าหนึ่ง
--    (จอต้องแยก "ยังไม่ระบุ" ออกจากคำตอบจริงเสมอ)

create table if not exists unit_sector (
  site_code text primary key,
  -- 🔴 CHECK คุมค่าให้เหลือสองค่าเท่านั้น — เคยเจอกับดัก CHECK บน source/result_scope
  --    มาแล้ว ถ้าจะเพิ่มค่าที่สาม (เช่น รัฐวิสาหกิจ) **ต้องมี migration ใหม่** ห้ามยัดค่าดิบ
  sector text not null check (sector in ('government', 'private')),
  updated_by uuid null,
  updated_by_name text null,
  updated_at timestamptz not null default now()
);

comment on table unit_sector is
  'ประเภทหน่วยงาน ราชการ/เอกชน ที่ทีมระบุเอง (เจ้าของเคาะ 25 ส.ค. 2569) — คีย์ site_code '
  'ไม่มีแถว = ยังไม่ระบุ · ไม่ derive จาก ERP เพราะ กฟภ./รัฐวิสาหกิจ เป็นเรื่องนโยบาย';

create index if not exists unit_sector_updated_at_idx on unit_sector (updated_at desc);
