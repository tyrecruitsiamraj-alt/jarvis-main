-- 🔴 **ทำไมต้องเก็บ ไม่ใช่คำนวณเอาจากลำดับ**
-- โหมด "ตั้งเวลาเป็นรอบ ๆ" สร้าง **หนึ่งแถวต่อหนึ่งรอบ** (ไม่ใช่หนึ่งแถวหลาย call_times)
-- แถวเดี่ยวจึงไม่มีข้อมูลว่าตัวเองเป็นรอบที่เท่าไหร่ ⇒ ตอนประกอบบทเลยใช้ "สายแรก" ทุกแถว
-- แม้จอจะเขียนว่ารอบ 2 ใช้บทรอบถัดไปก็ตาม (จอกับของจริงไม่ตรงกันมาตั้งแต่ 31 ส.ค. 2569)
-- คอลัมน์นี้ทำให้ "บทที่จอบอก" กับ "บทที่ AI พูดจริง" เป็นเรื่องเดียวกัน
--
-- สายที่ 1 = บทชุด `follow` (สายแรก) · สายที่ 2 ขึ้นไป = บทชุด `follow_repeat`
--
-- ⚠️ **ไม่ใส่ CHECK constraint** — บ้านนี้โดน CHECK ล็อกค่าใหม่มาสองรอบแล้ว
-- (source / result_scope) · ตรวจค่าที่ handler แทน แก้ง่ายกว่าและไม่ล็อกฐาน
-- ⚠️ nullable — แถวเก่าเป็น null ได้ = "ไม่ได้ระบุ" ⇒ โค้ดต้องอ่านเป็นสายที่ 1 เหมือนเดิม

alter table follow_entries
  add column if not exists call_round smallint;

comment on column follow_entries.call_round is
